def _glass_value(row: dict[str, Any]) -> str:
    material = str(row["material"] or "AIR").strip()
    compact = material.upper()
    if compact in {"AIR", "MIRROR"}:
        return compact
    nd = row.get("nd")
    vd = row.get("vd")
    if nd is None:
        return material
    if vd is None:
        return f"manual_n,{float(nd):.12g}"
    return f"nvk,{float(nd):.12g},{float(vd):.12g},0"


def _nearest_positive_sa(rows: list[dict[str, Any]], index: int) -> float:
    sa = rows[index].get("sa")
    if sa is not None and float(sa) > 0.0:
        return float(sa)
    for distance in range(1, len(rows) + 1):
        for candidate in (index - distance, index + distance):
            if 0 <= candidate < len(rows):
                value = rows[candidate].get("sa")
                if value is not None and float(value) > 0.0:
                    return float(value)
    return 12.5


def _advanced(row: dict[str, Any], figure: int) -> dict[str, Any]:
    source_sa = row.get("sa")
    material = str(row.get("material", "AIR"))
    note_parts = [
        f"{SOURCE_BOOK}, Figure 19.{figure}.",
        f"Source material: {material}.",
    ]
    if source_sa is not None:
        note_parts.append(f"Source semi-aperture: {float(source_sa):.12g} mm.")
    if row.get("note"):
        note_parts.append(str(row["note"]))
    advanced: dict[str, Any] = {"Note": " ".join(note_parts)}
    asphere = tuple(row.get("asphere") or ())
    if asphere:
        ad, ae, af, ag = (list(asphere) + [0.0] * 4)[:4]
        advanced["AspherData"] = [0.0, float(ad), float(ae), float(af), float(ag)]
    return advanced


def _surface_rows(design: dict[str, Any]) -> list[dict[str, Any]]:
    source_rows = list(design["rows"])
    max_sa = max((_nearest_positive_sa(source_rows, i) for i in range(len(source_rows))), default=12.5)
    object_distance = design.get("object_distance")
    object_thickness = (
        float(object_distance)
        if object_distance is not None
        else max(100.0, min(400.0, max_sa * 2.5))
    )
    result: list[dict[str, Any]] = [{
        "surface": "Object",
        "name": "Object",
        "rc": 0.0,
        "thickness": object_thickness,
        "diameter": max(25.0, 2.0 * max_sa),
        "glass": "AIR",
        "advanced": {
            "Note": (
                f"{SOURCE_BOOK}, Figure 19.{design['figure']}; "
                f"EFL {design['efl']:.12g} mm; BFL {design['bfl']:.12g} mm."
            )
        },
    }]

    element_number = 0
    in_element = False
    for index, row in enumerate(source_rows, start=1):
        material = str(row["material"] or "AIR").strip()
        is_air = material.upper() == "AIR"
        is_mirror = material.upper() == "MIRROR"
        source_stop = bool(row.get("stop"))
        sa = _nearest_positive_sa(source_rows, index - 1)
        diameter = max(0.1, 2.0 * sa)

        if source_stop and not is_air:
            result.append({
                "surface": "Aperture",
                "element": "",
                "name": f"S{index} Aperture Stop",
                "rc": 0.0,
                "thickness": 0.0,
                "diameter": diameter,
                "glass": "AIR",
                "advanced": _advanced(row, int(design["figure"])),
            })
            source_stop = False

        if not is_air and not is_mirror and not in_element:
            element_number += 1
            in_element = True
        element = f"E{element_number}" if in_element and not is_mirror else ""
        if is_air and in_element:
            # The medium printed on a prescription row is the space after that
            # surface, so the first AIR row is the closing face of the element.
            in_element = False
        elif is_mirror:
            element = ""
            in_element = False

        if source_stop:
            surface_type = "Aperture"
            name = f"S{index} Aperture Stop"
            glass = "AIR"
            radius = 0.0
        elif is_mirror:
            surface_type = "Mirror"
            name = f"S{index} Mirror"
            glass = "MIRROR"
            radius = float(row["radius"] or 0.0)
        else:
            surface_type = "Standard"
            radius = float(row["radius"] or 0.0)
            plane = " Plane" if row["radius"] is None else ""
            name = f"S{index}{plane} {material}"
            glass = _glass_value(row)

        result.append({
            "surface": surface_type,
            "element": element,
            "name": name,
            "rc": radius,
            "k": float(row.get("k", 0.0)),
            "thickness": float(row["thickness"]),
            "diameter": diameter,
            "glass": glass,
            "advanced": _advanced(row, int(design["figure"])),
        })

    image_diameter = max(1.0, 2.0 * abs(float(design["image_semiheight"])))
    result.append({
        "surface": "Image",
        "name": "Image",
        "rc": 0.0,
        "thickness": 0.0,
        "diameter": image_diameter,
        "glass": "AIR",
        "advanced": {
            "Note": (
                f"Figure 19.{design['figure']} Gaussian image semi-height "
                f"{design['image_semiheight']:.12g} mm."
            )
        },
    })
    return result


