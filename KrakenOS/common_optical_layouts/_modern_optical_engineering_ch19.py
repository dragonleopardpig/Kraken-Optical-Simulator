def r(
    radius: float | None,
    thickness: float,
    material: str = "AIR",
    nd: float | None = None,
    vd: float | None = None,
    sa: float | None = None,
    *,
    stop: bool = False,
    k: float = 0.0,
    asphere: tuple[float, float, float, float] = (),
    image_surface: bool = False,
    note: str = "",
) -> dict[str, Any]:
    """Compact source-row constructor.

    ``asphere`` is ``(AD, AE, AF, AG)`` = radial powers 4, 6, 8, and 10.
    """

    return {
        "radius": radius,
        "thickness": float(thickness),
        "material": material,
        "nd": nd,
        "vd": vd,
        "sa": sa,
        "stop": stop,
        "k": float(k),
        "asphere": tuple(asphere),
        "image_surface": image_surface,
        "note": note,
    }


